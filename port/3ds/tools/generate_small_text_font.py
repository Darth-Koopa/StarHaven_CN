#!/usr/bin/env python3
"""Generate a compact bitmap font atlas for the iQue 3DS small-text renderer.

The translation table stores CJK characters as private-use tokens indexed by
CHARSET_IQUE. This generator builds only the glyph subset used by translations,
plus printable ASCII, so the console can render localized UI before ROM font
assets are available. Pillow is required on the host only; the runtime uses no
TTF parser or dynamic font library.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_FONT = ROOT / "port/3ds/fonts/FusionPixel-10px-Mono-zh-Hans.ttf"
DEFAULT_CSV = ROOT / "port/3ds/localization/ui_translations_zh_CN.csv"
DEFAULT_OUT = ROOT / "port/3ds/gen/ui_small_font.h"
GLYPH_COUNT = 0x4F000 // 0x80
CELL = 16
COLS = 16
ROWS = 32
SLOTS = COLS * ROWS
ASCII_FIRST = 32
ASCII_LAST = 126
CJK_FIRST_SLOT = 128


def load_glyph_map() -> dict[str, int]:
    sys.path.insert(0, str(ROOT / "port/3ds/tools"))
    import generate_bottom_screen_translations as translations
    return translations.load_ique_character_map()


def c_array(name: str, ctype: str, values: list[int], per_line: int = 16) -> list[str]:
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    lines.append("};")
    return lines


def render_glyph(font: ImageFont.FreeTypeFont, ch: str, size: int) -> list[int]:
    image = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(image)
    bbox = draw.textbbox((0, 0), ch, font=font)
    left, top, right, bottom = bbox
    width, height = right - left, bottom - top
    # Center the actual glyph ink in the fixed monospaced cell while retaining
    # the font's pixel shape; the cell stays exactly 10x10 or 12x12.
    x = (size - width) // 2 - left
    y = (size - height) // 2 - top
    draw.text((x, y), ch, font=font, fill=255)
    return [image.getpixel((x, y)) for y in range(size) for x in range(size)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--size", type=int, choices=(10, 12), default=10)
    args = parser.parse_args()
    if not args.font.is_file():
        print(f"font file not found: {args.font}", file=sys.stderr)
        return 1

    rows = []
    with args.csv.open("r", encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    if not rows:
        print(f"translation CSV is empty: {args.csv}", file=sys.stderr)
        return 1

    char_to_glyph = load_glyph_map()
    target_chars = {ch for row in rows for ch in row["proposed_simplified_chinese"]}
    cjk_glyphs: dict[int, str] = {}
    for ch in target_chars:
        if ord(ch) <= 127:
            continue
        if ch not in char_to_glyph:
            print(f"missing iQue glyph mapping for {ch!r} U+{ord(ch):04X}", file=sys.stderr)
            return 1
        glyph = char_to_glyph[ch]
        previous = cjk_glyphs.setdefault(glyph, ch)
        if previous != ch:
            print(f"ambiguous native glyph index {glyph}: {previous!r} vs {ch!r}", file=sys.stderr)
            return 1

    glyph_count = len(cjk_glyphs)
    slot_count = CJK_FIRST_SLOT + glyph_count
    if slot_count > SLOTS:
        print(f"too many glyphs: {slot_count} slots exceed atlas capacity {SLOTS}", file=sys.stderr)
        return 1

    try:
        font = ImageFont.truetype(str(args.font), args.size)
    except Exception as exc:
        print(f"cannot open TTF {args.font}: {exc}", file=sys.stderr)
        return 1

    pixels = [0] * (SLOTS * args.size * args.size)
    for cp in range(ASCII_FIRST, ASCII_LAST + 1):
        try:
            glyph_pixels = render_glyph(font, chr(cp), args.size)
        except Exception as exc:
            print(f"failed to rasterize ASCII {cp}: {exc}", file=sys.stderr)
            return 1
        start = cp * args.size * args.size
        pixels[start:start + len(glyph_pixels)] = glyph_pixels

    glyph_slots = [0xFFFF] * GLYPH_COUNT
    for offset, glyph in enumerate(sorted(cjk_glyphs)):
        slot = CJK_FIRST_SLOT + offset
        glyph_slots[glyph] = slot
        ch = cjk_glyphs[glyph]
        glyph_pixels = render_glyph(font, ch, args.size)
        start = slot * args.size * args.size
        pixels[start:start + len(glyph_pixels)] = glyph_pixels

    out = [
        "/* Generated by tools/generate_small_text_font.py; do not edit by hand. */",
        "/* Fusion Pixel Font (SIL OFL 1.1); see fonts/LICENSE-OFL.txt. */",
        "#ifndef PM3DS_UI_SMALL_FONT_H",
        "#define PM3DS_UI_SMALL_FONT_H",
        f"#define PM3DS_SMALL_FONT_SIZE {args.size}",
        f"#define PM3DS_SMALL_FONT_CELL {CELL}",
        f"#define PM3DS_SMALL_FONT_ATLAS_COLS {COLS}",
        f"#define PM3DS_SMALL_FONT_ATLAS_ROWS {ROWS}",
        f"#define PM3DS_SMALL_FONT_ATLAS_W {CELL * COLS}",
        f"#define PM3DS_SMALL_FONT_ATLAS_H {CELL * ROWS}",
        f"#define PM3DS_SMALL_FONT_SLOT_COUNT {slot_count}",
        f"#define PM3DS_SMALL_FONT_GLYPH_PIXELS {args.size * args.size}",
        f"#define PM3DS_SMALL_FONT_IQUE_GLYPH_COUNT {GLYPH_COUNT}",
        "",
    ]
    # Store only used slots' pixel data so the source header remains small.
    used_slots = list(range(CJK_FIRST_SLOT + glyph_count))
    compact_pixels = []
    used_slot_to_compact = {slot: i for i, slot in enumerate(used_slots)}
    for slot in used_slots:
        start = slot * args.size * args.size
        compact_pixels.extend(pixels[start:start + args.size * args.size])
    out.append(f"static const unsigned char s_pm3ds_small_font_pixels[{len(used_slots)}][{args.size * args.size}] = {{")
    for i in range(len(used_slots)):
        row = compact_pixels[i * args.size * args.size:(i + 1) * args.size * args.size]
        out.append("    {" + ", ".join(str(v) for v in row) + "},")
    out.append("};")
    out.extend(c_array("s_pm3ds_ique_small_font_slots", "unsigned short", glyph_slots, per_line=16))
    out.extend(["#endif /* PM3DS_UI_SMALL_FONT_H */", ""])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"Generated {args.out}: {glyph_count} CJK/native glyphs + printable ASCII; {slot_count} slots, {args.size}x{args.size} pixels each.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
