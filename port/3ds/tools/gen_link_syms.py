#!/usr/bin/env python3
"""Generate port/3ds/m11_syms.ld (passed to the linker as an implicit script).

1. Effect shims: effect overlays call engine functions through shim_<fn>
   (src/effect_shims.yaml, an asm jump table on N64). Natively they are the
   same function, so alias them: shim_X = X.
2. Overlay address symbols (<seg>_ROM_START/_ROM_END/_VRAM) for segments the
   port links natively or has not ported yet. PROVIDE(sym = 0) only applies
   when nothing else defines the symbol. They all point at
   pm3ds_null_segment (m11_world_glue.c) -- 3dsxtool rejects relocations to
   absolute 0 -- and START == END makes any
   dma_copy() from them a zero-length no-op.
   Pass the link log to pick up the current undefined set:
       gen_link_syms.py build_world.log
"""
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
# PM3DS_VERSION=pal (m11_syms.ld) or us (m11_syms_us.ld), as for make
VER = os.environ.get("PM3DS_VERSION", "pal")
OUT = os.path.join(ROOT, "port", "3ds", "m11_syms%s.ld" % ("" if VER == "pal" else "_" + VER))
SEG_RE = re.compile(r"undefined reference to `(\w+_(?:ROM_START|ROM_END|VRAM))'")


def main():
    with open(os.path.join(ROOT, "src", "effect_shims.yaml")) as fh:
        shims = yaml.safe_load(fh)
    segs = set()
    if os.path.exists(OUT):  # keep previously collected symbols
        for line in open(OUT):
            m = re.match(r"PROVIDE\((\w+) = (?:0|pm3ds_null_segment)\);", line.strip())
            if m:
                segs.add(m.group(1))
    for log in sys.argv[1:]:
        segs |= set(SEG_RE.findall(open(log, errors="replace").read()))
    lines = ["/* GENERATED by port/3ds/tools/gen_link_syms.py -- do not edit */", ""]
    # functions the decomp renames with a function-like macro (include/functions.h):
    # the plain name would bind to a libc function of the same name (atan2!)
    renamed = {"atan2": "pm_atan2"}
    for s in shims:
        target = s[len("shim_"):]
        if target == "NULL":
            continue
        target = renamed.get(target, target)
        lines.append(f"PROVIDE({s} = {target});")
    lines.append("")
    for s in sorted(segs):
        lines.append(f"PROVIDE({s} = pm3ds_null_segment);")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(shims)} shims, {len(segs)} segment symbols -> {OUT}")


if __name__ == "__main__":
    main()
