#!/usr/bin/env python3
"""Link PAL, US, and official iQue builds into a single 3DS program.

Build each ROM target with PM3DS_GAME=1 first, then run this script inside
papermario-3ds-builder. PAL symbols remain unprefixed; US and iQue symbols are
renamed to us_* and ique_* so the three version-specific game copies cannot
bind to one another. Library symbols and linker-script symbols stay shared.
The starter detects normal US/PAL game IDs and the original iQue dump by its
known CRC32 because that dump's four-byte game-code field is blank.

usage: universal.py [out.elf] (default port/3ds/StarHaven_universal.elf)
"""
import concurrent.futures
import os
import re
import subprocess
import sys

PORT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BIN = "/opt/devkitpro/devkitARM/bin/arm-none-eabi-"
CTRU = "/opt/devkitpro/libctru"
PORTLIBS = "/opt/devkitpro/portlibs/3ds"
ARCH = ["-march=armv6k", "-mtune=mpcore", "-mfloat-abi=hard", "-mtp=soft"]
WORK = os.path.join(PORT, "build_universal")
COPIES = (
    ("us", "us_", "build_us", "PaperMario3DS_us.map", "m11_syms_us.ld"),
    ("ique", "ique_", "build_ique", "PaperMario3DS_ique.map", "m11_syms_ique.ld"),
)


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit("failed: %s\n%s%s" % (" ".join(cmd[:6]), r.stdout[-3000:], r.stderr[-3000:]))
    return r.stdout


def linked_objects(build_dir, mapfile):
    """Return object paths listed in the version's linker map LOAD records."""
    path = os.path.join(build_dir, mapfile)
    if not os.path.isfile(path):
        sys.exit("missing %s; build that version with PM3DS_GAME=1 first" % path)
    out = []
    for line in open(path, errors="replace"):
        if line.startswith("LOAD "):
            p = line[5:].strip()
            if p.endswith(".o") and not p.startswith("/"):
                out.append(os.path.join(build_dir, p))
    if not out:
        sys.exit("no object files found in %s" % path)
    return out


def global_symbols(objs):
    """Return defined and undefined global symbol names from object files."""
    defined, undefined = set(), set()
    for i in range(0, len(objs), 400):
        for line in run([BIN + "nm", "-g", "--no-sort"] + objs[i:i + 400]).splitlines():
            p = line.split()
            if len(p) == 2 and p[0] in ("U", "w", "v"):
                undefined.add(p[1])
            elif len(p) == 3:
                defined.add(p[2])
    return defined, undefined


def provided(ldscript):
    if not os.path.isfile(ldscript):
        sys.exit("missing linker symbol script: %s" % ldscript)
    return re.findall(r"PROVIDE\((\w+) = (\w+)\);", open(ldscript).read())


def prefix_copy(version, prefix, build_name, mapfile, ld_name):
    build_dir = os.path.join(PORT, build_name)
    objs = linked_objects(build_dir, mapfile)
    defined, undefined = global_symbols(objs)
    provides = provided(os.path.join(PORT, ld_name))

    rename = {s: prefix + s for s in defined | {a for a, _ in provides}}
    for s in list(rename):
        if s.startswith("__wrap_"):
            rename[s] = "__wrap_" + prefix + s[len("__wrap_"):]
    for s in undefined:
        if s.startswith("__real_"):
            rename[s] = "__real_" + prefix + s[len("__real_"):]

    mapfile_out = os.path.join(WORK, version + "_rename.txt")
    with open(mapfile_out, "w") as fh:
        fh.write("".join("%s %s\n" % kv for kv in sorted(rename.items())))
    print("%s copy: %d objects, %d symbols renamed" % (version.upper(), len(objs), len(rename)))

    def rewrite(src):
        dst = os.path.join(WORK, version, os.path.relpath(src, build_dir))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        run([BIN + "objcopy", "--redefine-syms=" + mapfile_out, src, dst])
        return dst

    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 8) as ex:
        new_objs = list(ex.map(rewrite, objs))

    ld_out = os.path.join(WORK, "m11_syms_" + version + "_universal.ld")
    with open(ld_out, "w") as fh:
        fh.write("/* GENERATED by tools/universal.py from %s -- do not edit */\n" % ld_name)
        for a, b in provides:
            fh.write("PROVIDE(%s = %s);\n" % (rename.get(a, a), rename.get(b, b)))
    return new_objs, ld_out


def main():
    out_elf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(PORT, "StarHaven_universal.elf")
    os.makedirs(WORK, exist_ok=True)
    pal_dir = os.path.join(PORT, "build")
    pal_objs = linked_objects(pal_dir, "PaperMario3DS.map")
    wraps = sorted(set(re.findall(r"--wrap=(\w+)", open(os.path.join(PORT, "Makefile")).read())))

    # PAL copy remains unprefixed; rename its entry point so starter.c owns main().
    pal_new = []
    for obj in pal_objs:
        if os.path.basename(obj) == "port_main.o":
            dst = os.path.join(WORK, "pal_port_main.o")
            run([BIN + "objcopy", "--redefine-sym", "main=pal_main", obj, dst])
            obj = dst
        pal_new.append(obj)

    copied_objs = []
    copied_linker_scripts = []
    prefixes = []
    for version, prefix, build_name, mapfile, ld_name in COPIES:
        objs, ld = prefix_copy(version, prefix, build_name, mapfile, ld_name)
        copied_objs.extend(objs)
        copied_linker_scripts.append(ld)
        prefixes.append(prefix)

    starter = os.path.join(WORK, "starter.o")
    run([BIN + "gcc", "-O2", "-g", "-Wall", "-mword-relocations", "-ffunction-sections", "-fdata-sections"] + ARCH +
        ["-D__3DS__", "-I" + os.path.join(PORT, "include"), "-I" + CTRU + "/include",
         "-c", os.path.join(PORT, "universal", "starter.c"), "-o", starter])

    rsp = os.path.join(WORK, "link.rsp")
    with open(rsp, "w") as fh:
        fh.write("\n".join([starter] + pal_new + copied_objs) + "\n")
    wrap_flags = []
    for w in wraps:
        wrap_flags.append("-Wl,--wrap=" + w)
        for prefix in prefixes:
            wrap_flags.append("-Wl,--wrap=" + prefix + w)
    cmd = ([BIN + "gcc", "-specs=3dsx.specs", "-g"] + ARCH +
           ["-Wl,-Map," + os.path.join(WORK, "universal.map")] + wrap_flags +
           ["@" + rsp, os.path.join(PORT, "m11_syms.ld")] + copied_linker_scripts +
           ["-L" + PORTLIBS + "/lib", "-lcurl", "-lmbedtls", "-lmbedx509", "-lmbedcrypto", "-lz",
            "-L" + CTRU + "/lib", "-lcitro3d", "-lctru", "-lm", "-o", out_elf])
    run(cmd)
    print("linked", out_elf)
    print(run([BIN + "size", out_elf]))


if __name__ == "__main__":
    main()
