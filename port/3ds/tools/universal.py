#!/usr/bin/env python3
"""Link the PAL and the US build of the game into one program.

A release package runs with either ROM, but the decomp compiles differently
per version, so the program holds both builds and universal/starter.c picks
one at run time from the ROM's header. Run inside the papermario-3ds-builder
image after both versions are built (make PM3DS_GAME=1 for pal, then with
PM3DS_VERSION=us); the object lists come from their linker maps.

  * PAL copy: its objects as linked, main() renamed pal_main.
  * US copy: every global symbol its objects define, and every symbol its
    m11_syms_us.ld provides, gets a us_ prefix (objcopy --redefine-syms), so
    the copies never bind to each other. Library symbols (libctru, citro3d,
    newlib, libgcc) and linker-script symbols stay shared. --wrap pairs keep
    working: __wrap_X -> __wrap_us_X, __real_X -> __real_us_X.
  * starter.o provides main().

usage (in the image): universal.py [out.elf]   (default port/3ds/StarHaven_universal.elf)
"""
import concurrent.futures
import os
import re
import subprocess
import sys

PORT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BIN = "/opt/devkitpro/devkitARM/bin/arm-none-eabi-"
CTRU = "/opt/devkitpro/libctru"
PORTLIBS = "/opt/devkitpro/portlibs/3ds"
ARCH = ["-march=armv6k", "-mtune=mpcore", "-mfloat-abi=hard", "-mtp=soft"]
WORK = os.path.join(PORT, "build_universal")
PREFIX = "us_"


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit("failed: %s\n%s%s" % (" ".join(cmd[:6]), r.stdout[-3000:], r.stderr[-3000:]))
    return r.stdout


def linked_objects(build_dir, mapfile):
    """the objects a version's link used, from its map's LOAD lines"""
    out = []
    for line in open(os.path.join(build_dir, mapfile), errors="replace"):
        if line.startswith("LOAD "):
            p = line[5:].strip()
            if p.endswith(".o") and not p.startswith("/"):
                out.append(os.path.join(build_dir, p))
    return out


def global_symbols(objs):
    """(defined, undefined) global symbol names over a list of objects"""
    defined, undefined = set(), set()
    for i in range(0, len(objs), 400):
        for line in run([BIN + "nm", "-g", "--no-sort"] + objs[i:i + 400]).splitlines():
            p = line.split()
            if len(p) == 2 and p[0] in ("U", "w", "v"):
                undefined.add(p[1])
            elif len(p) == 3:
                defined.add(p[2])
    return defined, undefined


def provided(ldscript):
    return re.findall(r"PROVIDE\((\w+) = (\w+)\);", open(ldscript).read())


def main():
    out_elf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(PORT, "StarHaven_universal.elf")
    os.makedirs(WORK, exist_ok=True)
    pal_objs = linked_objects(os.path.join(PORT, "build"), "PaperMario3DS.map")
    us_objs = linked_objects(os.path.join(PORT, "build_us"), "PaperMario3DS_us.map")
    wraps = sorted(set(re.findall(r"--wrap=(\w+)", open(os.path.join(PORT, "Makefile")).read())))

    # the US copy's rename map
    defined, undefined = global_symbols(us_objs)
    us_provides = provided(os.path.join(PORT, "m11_syms_us.ld"))
    rename = {s: PREFIX + s for s in defined | {a for a, _ in us_provides}}
    for s in list(rename):
        if s.startswith("__wrap_"):
            rename[s] = "__wrap_" + PREFIX + s[len("__wrap_"):]
    for s in undefined:
        if s.startswith("__real_"):
            rename[s] = "__real_" + PREFIX + s[len("__real_"):]
    mapfile = os.path.join(WORK, "us_rename.txt")
    with open(mapfile, "w") as fh:
        fh.write("".join("%s %s\n" % kv for kv in sorted(rename.items())))
    print("US copy: %d objects, %d symbols renamed" % (len(us_objs), len(rename)))

    def rewrite(src):
        dst = os.path.join(WORK, "us", os.path.relpath(src, os.path.join(PORT, "build_us")))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        run([BIN + "objcopy", "--redefine-syms=" + mapfile, src, dst])
        return dst
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 8) as ex:
        us_new = list(ex.map(rewrite, us_objs))

    # the PAL copy: as linked, with its main() renamed for the starter
    pal_new = []
    for o in pal_objs:
        if os.path.basename(o) == "port_main.o":
            dst = os.path.join(WORK, "pal_port_main.o")
            run([BIN + "objcopy", "--redefine-sym", "main=pal_main", o, dst])
            o = dst
        pal_new.append(o)

    # the US copy's link-time symbols, renamed the same way
    us_ld = os.path.join(WORK, "m11_syms_us_universal.ld")
    with open(us_ld, "w") as fh:
        fh.write("/* GENERATED by tools/universal.py from m11_syms_us.ld -- do not edit */\n")
        for a, b in us_provides:
            fh.write("PROVIDE(%s = %s);\n" % (rename.get(a, a), rename.get(b, b)))

    starter = os.path.join(WORK, "starter.o")
    run([BIN + "gcc", "-O2", "-g", "-Wall", "-mword-relocations", "-ffunction-sections", "-fdata-sections"] + ARCH +
        ["-D__3DS__", "-I" + os.path.join(PORT, "include"), "-I" + CTRU + "/include",
         "-c", os.path.join(PORT, "universal", "starter.c"), "-o", starter])

    rsp = os.path.join(WORK, "link.rsp")
    with open(rsp, "w") as fh:
        fh.write("\n".join([starter] + pal_new + us_new) + "\n")
    cmd = ([BIN + "gcc", "-specs=3dsx.specs", "-g"] + ARCH +
           ["-Wl,-Map," + os.path.join(WORK, "universal.map")] +
           ["-Wl,--wrap=" + w for w in wraps] + ["-Wl,--wrap=" + PREFIX + w for w in wraps] +
           ["@" + rsp, os.path.join(PORT, "m11_syms.ld"), us_ld,
            "-L" + PORTLIBS + "/lib", "-lcurl", "-lmbedtls", "-lmbedx509", "-lmbedcrypto", "-lz",   # update check
            "-L" + CTRU + "/lib", "-lcitro3d", "-lctru", "-lm", "-o", out_elf])
    run(cmd)
    print("linked", out_elf)
    print(run([BIN + "size", out_elf]))


if __name__ == "__main__":
    main()
