#!/usr/bin/env python3
"""Generate port/3ds/source/n64_shim/fx_shims.c from src/effects.yaml.

Upstream fx_<name> is an asm trampoline (tools/splat_ext/pm_effect_loads.py):
load_effect(index), then tail-call gEffectTable[index].entryPoint with the
caller's arguments. Effect code is compiled natively on the port, so the C
equivalent calls <name>_main directly with the real prototype. (The previous
variadic `(int, ...)` decls passed floats as doubles in core registers on ARM
hard-float, which the non-variadic *_main read from VFP registers.)
"""
import os

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def main():
    with open(os.path.join(ROOT, "src", "effects.yaml")) as fh:
        effects = yaml.safe_load(fh)
    out = [
        "/* GENERATED by port/3ds/tools/gen_fx_shims.py from src/effects.yaml -- do not edit */",
        '#include "common.h"',
        '#include "effects.h"',
        "",
        "s32 load_effect(s32 effectIndex);",
        "",
    ]
    for idx, eff in enumerate(effects):
        if not eff or "name" not in eff:
            continue
        name = eff["name"]
        args = [a.strip() for a in str(eff.get("args", "")).split(",") if a.strip()]
        params = ", ".join(f"{t} a{i}" for i, t in enumerate(args)) or "void"
        call = ", ".join(f"a{i}" for i in range(len(args)))
        ret = "void" if eff.get("void", False) else "EffectInstance*"
        ret_kw = "" if ret == "void" else "return "
        out.append(f"EFFECT_DEF_{name.upper()}({name}_main);")
        out.append(f"{ret} fx_{name}({params}) {{")
        out.append(f"    load_effect(0x{idx:02X});")
        out.append(f"    {ret_kw}{name}_main({call});")
        out.append("}")
        out.append("")
    dst = os.path.join(ROOT, "port", "3ds", "source", "n64_shim", "fx_shims.c")
    with open(dst, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
