#!/usr/bin/env python3
"""Generate port/3ds/world_files.mk: the decomp world-map translation units.

On N64 every map is a separate overlay DMA'd to 0x80240000 and its MIPS code
is jumped into. That cannot work on 3DS, so the port compiles every map's C
natively and points MapConfig at the native symbols (dmaStart = NULL).

The file list comes from the PAL splat config (`c` subsegments under
world/area_*), which is what the upstream build links into each overlay.
A directory scan is not enough: some files are version-specific (hos_10's
narrator.c is JP-only) and some are #included by siblings.
Object paths keep the directory so the hundreds of main.c / npc.c /
settings.c files do not collide by basename.
"""
import os
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
# PM3DS_VERSION=pal (world_files.mk) or us (world_files_us.mk), as for make
VER = os.environ.get("PM3DS_VERSION", "pal")
SPLAT = os.path.join(ROOT, "ver", VER, "splat.yaml")
PREFIXES = tuple(sys.argv[1:]) or (
    # every map overlay + the world code that isn't top-level src/world/*.c
    "world/area_", "world/script_api/", "world/action/", "world/partner/",
    "world/model_anim/",
    # entity models/scripts, effect graphics data
    "entity/", "effects/gfx/",
    # battle areas, moves, action commands, partners
    "battle/area/", "battle/move/", "battle/action_cmd/", "battle/partner/",
    "battle/common/",
    # libultra gu* matrix math written in C (the asm ones live in
    # source/n64_shim/gu_impl.c, emitting the port's s15.16 Mtx layout)
    "os/gu", "os/sins", "os/coss", "os/perspective", "os/position",
    "os/rotateRPY", "os/lookat", "os/frustum",
    # the N64 audio engine (M14); command lists run on audio_alist.c
    "audio/core/",
)
# Translation units upstream builds from non-`c` subsegments (vtx data that a
# hand-written .c wraps); splat does not list them as `c`.
EXTRA_TUS = ["battle/area/sam2/vtx.c"]
# Replaced by port code (nusys scheduler/DMA plumbing): audio_system.c
EXCLUDE_TUS = {"audio/core/system.c"}

WILDCARD_DIRS = {"gcc", "charset", "common", "evt", "entity", "effects", "world",
                 "battle", "pause", "filemenu", "audio", "", "bss"}


def main():
    with open(SPLAT) as fh:
        cfg = yaml.safe_load(fh)
    tus = []

    def walk(seg, base):
        if isinstance(seg, dict):
            for sub in seg.get("subsegments", []) or []:
                walk(sub, seg.get("dir", base))
            return
        if isinstance(seg, list) and len(seg) >= 3 and seg[1] == "c":
            path = os.path.normpath(os.path.join(base, f"{seg[2]}.c"))
            if path.startswith(PREFIXES):
                tus.append(path)

    for seg in cfg["segments"]:
        walk(seg, "")
    # Files directly inside the Makefile's SOURCES dirs are already built by
    # the basename wildcard; listing them here would define them twice.
    tus = sorted(t for t in set(tus) | set(EXTRA_TUS) if os.path.dirname(t) not in WILDCARD_DIRS and t not in EXCLUDE_TUS)
    missing = [t for t in tus if not os.path.exists(os.path.join(ROOT, "src", t))]
    if missing:
        sys.exit(f"missing sources: {missing[:5]}")
    out = os.path.join(ROOT, "port", "3ds", "world_files%s.mk" % ("" if VER == "pal" else "_" + VER))
    with open(out, "w") as fh:
        fh.write(f"# GENERATED by tools/gen_world_files.py from ver/{VER}/splat.yaml -- do not edit\n")
        fh.write("WORLD_CFILES := \\\n")
        for t in tus:
            fh.write(f"\t{t} \\\n")
        fh.write("\n")
    print(f"{len(tus)} translation units -> {out}")


if __name__ == "__main__":
    main()
