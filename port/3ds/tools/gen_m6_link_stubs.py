#!/usr/bin/env python3
"""Generate weak stubs for symbols undefined when boot_main is linked in.

Reads a list of undefined-symbol names (one per line) from stdin or a
file argument and writes a single .c file with a weak function stub
per symbol. The address of each stub doubles as a data value for
struct-table references (e.g. partner_dma.o's table of partner script
function pointers), so this satisfies the linker for both call sites
and data-table fixups.

Runtime behaviour: any code that dereferences these symbols as structs
will read instruction bytes as struct members, which is garbage. The
purpose of M6.1 is to make the build *link*, not to make it *run* the
real game logic. Per-area / per-partner real implementations are M7+.

M9 WARNING -- this is sharper than "garbage", and it has already cost one
multi-session bug. For a DATA symbol these stubs are actively dangerous:

  * Each stub is only 4 bytes. A declared type larger than that reads
    straight through into the FOLLOWING stubs, so the fields come back as
    a run of ARM `bx lr` encodings (0xE12FFF1E). Reinterpreted as s16
    that is -226 / -7889 -- small, plausible-looking, SIGNED numbers, not
    obviously-wrong values. `gBackgroundImage` did exactly this and drove
    a display-list loop 876 iterations long into a 512-entry buffer,
    which tripped a bounds ASSERT that (being a non-DEBUG build) hung the
    main thread silently. Nothing in the failure pointed at this file.

  * Worse, the stubs live in read-only .text, so any code that WRITES the
    symbol faults on real hardware. Azahar does not enforce this, so the
    port can look fine in the emulator and fail on a real 3DS.
    (`gRandSeed += osGetCount()` in src/main.c was doing this every boot.)

So: before adding a symbol here, check whether the decomp declares it as
data. If it does, give it real storage in n64_shim/m9_data_syms.c and add
it to SKIP below instead. The audit command is in that file's header.

Usage:
    python3 gen_m6_link_stubs.py undef_list.txt > m6_link_stubs.c
"""

import sys
from pathlib import Path


HEADER = """\
/*
 * m6_link_stubs.c -- auto-generated by tools/gen_m6_link_stubs.py
 *
 * Provides weak function stubs for every symbol that becomes
 * unresolved when src/main.c's boot_main is pulled into the link.
 * Each stub has a unique address so data tables that take the
 * symbol's address as a function pointer (battle_partner_*,
 * action_update_*, etc.) get a valid pointer at link time.
 *
 * Calling any of these stubs at runtime is a no-op. Reading their
 * bytes as struct data (which the game's data tables expect) yields
 * garbage. M6.1's purpose is to make the build LINK with boot_main
 * referenced; runtime correctness is M6.2+ work.
 *
 * Regenerate after each link-failure cycle by extracting the
 * "undefined reference to NAME" list from build output and feeding
 * it to tools/gen_m6_link_stubs.py.
 */

"""


def main() -> int:
    if len(sys.argv) < 2:
        sys.stderr.write("usage: gen_m6_link_stubs.py <undef_list.txt>\n")
        return 1

    path = Path(sys.argv[1])
    # Symbols already provided with specific prototypes in
    # include_asm.h — we can't emit them as `void name(void)` because
    # gcc's "conflicting types" error fires. They get hand-typed
    # implementations in port/3ds/source/n64_shim/m4_stubs.c.
    SKIP = {
        'osMapTLB', 'osUnmapTLB', 'osUnmapTLBAll',
        'osFlashInit', 'osFlashReadArray', 'osFlashWriteArray',
        'osFlashWriteBuffer', 'osFlashSectorErase',
        # M8: real impl in port/3ds/source/n64_shim/nugfx_task.c
        'nuGfxTaskStart',
        # M9: these are DATA, not functions. Emitting `void sym(void) {}` puts
        # them in read-only .text, so struct reads return ARM instruction bytes
        # (and overrun into the NEXT stubs when the type is >4 bytes) and any
        # write faults on real hardware. This is what caused the M9
        # title-screen hang via gBackgroundImage. Real storage lives in
        # n64_shim/m9_background_shim.c and n64_shim/m9_data_syms.c.
        'gBackgroundImage',
        'gRandSeed',
        'heap_battleHead',
        'osViModeFpalLpn1',
        # Declared in src/audio.h, not include/ -- these are POINTERS, so the
        # stub's instruction word gets used as an address and written through
        # (au_sfx_set_state -> `manager->state = state`). Audit headers
        # everywhere, not just include/.
        'gSoundManager',
        'gBGMPlayerA',
        'gBGMPlayerB',
        'gAuAmbienceManager',
    }

    symbols = sorted({
        line.strip() for line in path.read_text().splitlines()
        if line.strip() and not line.startswith('#') and line.strip() not in SKIP
    })

    sys.stderr.write(f"generating stubs for {len(symbols)} symbols\n")

    sys.stdout.write(HEADER)
    sys.stdout.write(f"/* {len(symbols)} symbols stubbed */\n\n")

    for sym in symbols:
        sys.stdout.write(
            f'__attribute__((weak)) void {sym}(void) {{}}\n'
        )

    return 0


if __name__ == '__main__':
    sys.exit(main())
