#!/usr/bin/env python3
"""
Port-side standalone generator for `include/sprite/player.h`.

Upstream uses tools/build/sprite/sprites.py which produces the header as a
side effect of building the full sprite blob (compressed CI4 rasters etc.).
For M4 we only need the ANIM_*/SPR_*/SPR_IMG_*/SPR_PAL_* defines so callers
in src/evt/player_api.c etc. compile. The compressed sprite blob is M5+.

Reads assets/pal/sprite/player.xml (the sprite-order manifest) and per-sprite
XMLs in assets/pal/sprite/player/<name>.xml, and writes the macro/enum
definitions to include/sprite/player.h.

This is a strict subset of tools/build/sprite/sprites.py:write_player_sprite_header
— same numeric encoding (sprite_id << 16 | palette_id << 8 | anim_id) — but
omits MAX_IMG_<sprite> (which needs raster sizes) by emitting it as 0.
"""

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("manifest", type=Path, help="assets/<ver>/sprite/player.xml")
    p.add_argument("out", type=Path, help="include/sprite/player.h")
    args = p.parse_args()

    manifest = ET.parse(args.manifest).getroot()
    sprite_dir = args.manifest.parent / "player"

    sprite_id = 1
    player_sprites = []
    player_rasters = {}
    player_palettes = {}
    player_anims = {}

    sprite_order = []
    for sprite_xml_elem in manifest.findall(".//Sprite"):
        # manifest entries look like <Sprite name="Mario1"/>; the sprite XML
        # lives at <manifest-dir>/player/<name>.xml.
        sprite_order.append(sprite_xml_elem.attrib["name"])

    for sprite_name in sprite_order:
        xml_path = sprite_dir / f"{sprite_name}.xml"
        sprite_xml = ET.parse(xml_path).getroot()
        has_back = sprite_xml.attrib.get("hasBack", "false") == "true"

        anim_elems = sprite_xml.findall("./AnimationList/Animation")
        img_elems = sprite_xml.findall("./RasterList/Raster")
        pal_elems = sprite_xml.findall("./PaletteList/Palette")

        player_sprites.append((f"SPR_{sprite_name}", sprite_id))
        player_rasters[sprite_name] = []
        player_palettes[sprite_name] = []
        player_anims[sprite_name] = []

        for palette_xml in pal_elems:
            palette_id = int(palette_xml.attrib["id"], 16)
            palette_name = palette_xml.attrib["name"]
            player_palettes[sprite_name].append(
                (f"SPR_PAL_{sprite_name}_{palette_name}", palette_id)
            )
            for anim_id, anim_xml in enumerate(anim_elems):
                anim_name = anim_xml.attrib["name"]
                if palette_id > 0:
                    anim_name = f"{palette_name}_{anim_name}"
                player_anims[sprite_name].append(
                    (
                        f"ANIM_{sprite_name}_{anim_name}",
                        (sprite_id << 16) | (palette_id << 8) | anim_id,
                    )
                )

        for raster_xml in img_elems:
            raster_id = int(raster_xml.attrib["id"], 16)
            raster_name = raster_xml.attrib["name"]
            player_rasters[sprite_name].append(
                (f"SPR_IMG_{sprite_name}_{raster_name}", raster_id)
            )

        sprite_id += 1
        if has_back:
            player_sprites.append((f"SPR_{sprite_name}_Back", sprite_id))
            sprite_id += 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w") as f:
        f.write("#ifndef _SPRITE_PLAYER_H_\n#define _SPRITE_PLAYER_H_\n\n")
        f.write("/* Generated by port/3ds/tools/gen_player_sprite_header.py — do not edit. */\n\n")
        f.write("enum PlayerSprites {\n")
        for name, sid in player_sprites:
            f.write(f"    {name} = 0x{sid:X},\n")
        f.write("};\n\n")

        for name, _ in player_sprites:
            sprite_only = name[len("SPR_"):]
            f.write(f"#define MAX_IMG_{sprite_only} 0x0000\n")
        f.write("\n")

        for sprite_name in sprite_order:
            f.write(f"// {sprite_name}\n")
            for raster_name, raster_id in player_rasters[sprite_name]:
                f.write(f"#define {raster_name} 0x{raster_id:02X}\n")
            f.write("\n")
            for pal_name, pid in player_palettes[sprite_name]:
                f.write(f"#define {pal_name} 0x{pid:02X}\n")
            f.write("\n")
            for anim_name, aid in player_anims[sprite_name]:
                f.write(f"#define {anim_name} 0x{aid:X}\n")
            f.write("\n")

        f.write("#endif // _SPRITE_PLAYER_H_\n")


if __name__ == "__main__":
    main()
